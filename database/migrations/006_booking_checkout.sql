-- Purpose: purchases (API contract v1.0, section 6, with Stripe test
--          payments as required by the course):
--          POST /bookings, GET /bookings/:reference, GET /me/bookings,
--          POST /api/stripe/webhook.
-- Apply after 001-005. Adds columns, one table, constraints and indexes
-- only; no existing rows are changed and no table is dropped.
--
-- Design
-- * A purchase turns one checkout hold into one booking, in one transaction
--   that locks the screening row first (same order as holds):
--     bookings       (one row, with snapshots)
--     booking_seats  (one row per seat, ticket type and price in euros)
--     payments       (one row: method 'stripe' or 'simulated')
--     checkout_holds -> status 'consumed'; its seat_holds -> 'released'.
--   From then on the seat is protected by uq_booking_seats_screening_seat.
-- * Stripe: the booking starts as 'pending' with expires_at = the Stripe
--   Checkout Session expiry. Only a verified Stripe webhook makes it
--   'confirmed' (checkout.session.completed). checkout.session.expired
--   makes it 'expired' and deletes its booking_seats, so the seats are
--   free again. A pending booking whose expiry has passed stops holding
--   its seats even if the webhook is late (lazy expiry).
-- * stripe_events stores every processed Stripe event ID, so a repeated
--   webhook delivery never changes a booking twice.
-- * Simulated payment ('confirmed' at once) is kept for tests and demos and
--   is switched off unless ALLOW_SIMULATED_PAYMENT=true on the backend.
-- * Snapshots: the booking keeps the movie title, poster, cinema, room,
--   start time, ticket counts, prices and seat labels as they were at
--   purchase time, so later movie or price changes never alter a receipt.
-- * Contact: contact_name / contact_email are the checkout contact. They
--   never overwrite the customer's account name or email.
-- * Ownership: user_id for customers. session_id is for guest receipts
--   (used when anonymous sessions arrive); is_guest records whether an
--   account owned the purchase when it was made.
-- * reference: opaque, unique, generated by the backend (e.g. RIO-7KQ2M9XA).

BEGIN;

ALTER TABLE bookings
    ADD COLUMN reference          VARCHAR(20),
    ADD COLUMN checkout_hold_id   INTEGER REFERENCES checkout_holds(checkout_hold_id) ON DELETE RESTRICT,
    ADD COLUMN session_id         INTEGER REFERENCES sessions(session_id) ON DELETE SET NULL,
    ADD COLUMN is_guest           BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN contact_name       VARCHAR(100),
    ADD COLUMN contact_email      VARCHAR(254),
    -- purchase-time snapshots
    ADD COLUMN movie_id           INTEGER REFERENCES movies(movie_id) ON DELETE RESTRICT,
    ADD COLUMN movie_title        VARCHAR(255),
    ADD COLUMN movie_poster_url   VARCHAR(500),
    ADD COLUMN theater_id         INTEGER REFERENCES theaters(theater_id) ON DELETE RESTRICT,
    ADD COLUMN cinema_name        VARCHAR(100),
    ADD COLUMN cinema_city        VARCHAR(100),
    ADD COLUMN room_id            INTEGER REFERENCES rooms(room_id) ON DELETE RESTRICT,
    ADD COLUMN room_name          VARCHAR(50),
    ADD COLUMN starts_at          TIMESTAMPTZ,
    ADD COLUMN adult_count        INTEGER CHECK (adult_count >= 0),
    ADD COLUMN child_count        INTEGER CHECK (child_count >= 0),
    ADD COLUMN adult_unit_cents   INTEGER CHECK (adult_unit_cents >= 0),
    ADD COLUMN child_unit_cents   INTEGER CHECK (child_unit_cents >= 0),
    ADD COLUMN total_cents        INTEGER CHECK (total_cents >= 0),
    -- Stripe Checkout (test mode)
    ADD COLUMN payment_method           VARCHAR(20) CHECK (payment_method IN ('stripe', 'simulated')),
    ADD COLUMN stripe_session_id        VARCHAR(255),
    ADD COLUMN stripe_checkout_url      TEXT,
    ADD COLUMN stripe_payment_intent_id VARCHAR(255);

ALTER TABLE bookings ADD CONSTRAINT uq_bookings_stripe_session UNIQUE (stripe_session_id);

-- Processed Stripe webhook events (each event ID is handled once).
CREATE TABLE stripe_events (
    event_id    VARCHAR(255) PRIMARY KEY,
    event_type  VARCHAR(100) NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- One booking per reference and per checkout hold (a hold is bought once).
ALTER TABLE bookings ADD CONSTRAINT uq_bookings_reference UNIQUE (reference);
ALTER TABLE bookings ADD CONSTRAINT uq_bookings_checkout_hold UNIQUE (checkout_hold_id);

-- Bookings made through checkout always carry a reference and a contact.
-- Older rows (reference IS NULL) are not affected.
ALTER TABLE bookings ADD CONSTRAINT chk_bookings_checkout_fields CHECK (
    reference IS NULL
    OR (contact_name IS NOT NULL AND contact_email IS NOT NULL
        AND movie_title IS NOT NULL AND starts_at IS NOT NULL
        AND adult_count IS NOT NULL AND child_count IS NOT NULL
        AND total_cents IS NOT NULL AND payment_method IS NOT NULL)
);

-- Seat labels as printed on the receipt.
ALTER TABLE booking_seats
    ADD COLUMN seat_label VARCHAR(10),
    ADD COLUMN row_label  VARCHAR(10);

-- GET /me/bookings: newest first per customer.
CREATE INDEX idx_bookings_user_created ON bookings(user_id, created_at DESC, booking_id DESC);
CREATE INDEX idx_bookings_session_id ON bookings(session_id);
-- Lazy expiry of unpaid Stripe bookings.
CREATE INDEX idx_bookings_pending_expiry ON bookings(screening_id, expires_at) WHERE booking_status = 'pending';

COMMIT;
